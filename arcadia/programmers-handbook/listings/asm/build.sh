#!/usr/bin/env bash
# build.sh -- this handbook's 2650 programs, with Macroassembler AS.
#
#   ./build.sh                    every program
#   ./build.sh netget clock       just those
#
# Each program becomes build/<name>.bin, the 8192-byte image the cartridge
# serves (bank: 8K + 3 APPBANK pages). The runtime (../runtime) is the
# firmware's testrom, verbatim, and is assembled exactly as the firmware's
# build.sh does it: asl, then p2bin over $0000-$2FFF, then mkimage folds the
# two 4K blocks into the image, then the "FUJI" claim at 0x1CFC, then
# checkrom and checkdepth. build/gen/bookcfg.inc carries the bench's URLs.
set -euo pipefail
cd "$(dirname "$0")"
BOOK=$(cd ../.. && pwd)
. "$BOOK/bench/ports.env"

if command -v asl >/dev/null 2>&1; then ASL=asl P2BIN=p2bin
else ASL=$HOME/asl/asl P2BIN=$HOME/asl/p2bin; fi
[ -x "$(command -v "$ASL")" ] || { echo "build.sh: no asl" >&2; exit 1; }
TOOLS=../runtime/tools
mkdir -p build/gen build/obj ../build

HOST=${HOST:-127.0.0.1}
cat > build/gen/bookcfg.inc <<EOC
; GENERATED by build.sh -- do not edit.
HTTPURL MACRO
        DB      "N:http://$HOST:$HTTP_PORT/hello.txt", 0
        ENDM
NCURL   MACRO
        DB      "N:TCP://$HOST:$NC_PORT/", 0
        ENDM
EOC
# fujiboot's own configuration, as the firmware's build.sh writes it; the
# runtime's fujiboot.asm includes it as ../build/bootcfg.inc
{
    echo "; generated by build.sh -- do not edit"
    echo "BOOTHST EQU     ${BOOT_HOST:-0}"
    printf 'BOOTPTH:DB      "%s"\n' "${BOOT_PATH:-/arcbook/hello.bin}"
    echo "        DB      0"
} > ../build/bootcfg.inc

pages_of() {   # APPBANK pages past the base 8K
    case $1 in bank|fujibank) echo 3 ;; *) echo 0 ;; esac
}

build_one() {
    local name=$1 src
    if [ -f "$name.asm" ]; then src=.; else src=../runtime; fi
    [ -f "$src/$name.asm" ] || { echo "build.sh: no $name.asm" >&2; exit 1; }
    # relative paths: AS truncates a long include list
    local r obj pages
    r=$(realpath --relative-to="$src" .)
    obj=build/obj/$name
    (cd "$src" && "$ASL" -q -L -i "$r:$r/../runtime:$r/build/gen" \
        -o "$r/$obj.p" -olist "$r/$obj.lst" "$name.asm")
    pages=$(pages_of "$name")
    "$P2BIN" -q "$obj.p" "$obj.flat" \
        -r "\$0000-\$$(printf '%04X' $((0x3000 + pages * 0x800 - 1)))" -l 0
    if [ "$pages" -gt 0 ]; then
        python3 "$TOOLS/mkimage.py" --pages "$pages" "$obj.flat" "build/$name.bin"
    else
        python3 "$TOOLS/mkimage.py" "$obj.flat" "build/$name.bin"
    fi
    printf 'FUJI' | dd of="build/$name.bin" bs=1 seek=$((0x1CFC)) \
        conv=notrunc status=none
    python3 "$TOOLS/checkrom.py" "build/$name.bin"
    # the call graph: the program and everything it includes
    local incs
    incs=$(sed -n 's/^[[:space:]]*INCLUDE[[:space:]]*"\([^"]*\)".*/\1/p' "$src/$name.asm" \
        | while read -r f; do
            for d in "$src" . ../runtime build/gen; do
                [ -f "$d/$f" ] && { echo "$d/$f"; break; }
            done
          done)
    # shellcheck disable=SC2086
    python3 "$TOOLS/checkdepth.py" "$src/$name.asm" $incs | sed "s/^/$name: /"
    # and the book's stricter count (falls-through and branches too)
    python3 "$BOOK/tools/depthcheck.py" -I ../runtime -I . -I build/gen "$src/$name.asm"
}

targets=("$@")
[ ${#targets[@]} -gt 0 ] || targets=(hello fujitest pads netget netcat fujidir fujiboot appkey clock sprites fujibank)
for t in "${targets[@]}"; do
    build_one "$t"
done
