#!/usr/bin/env bash
# build.sh -- assemble Battleship for the RCA Studio II with Macroassembler AS.
#
#   ./build.sh                                     build/battleship.st2
#   ENDPOINT=http://127.0.0.1:8080/ ./build.sh     another server
#   DEMO=1 ./build.sh                              a canned four-seat game, no
#                                                  network: the layout and tiles
#
# Everything lands in build/. The checker and the ST2 packer come from the
# cartridge bring-up in the firmware tree (pico/studio2/tools): checkrom.py
# refuses a 3-cycle opcode or RF used as anything but an LDN pointer, and
# mkst2.py refuses code on a page an app may not claim. The boards are drawn
# with the cart text engine's mosaic cells (TOP_TILE / TOP_MOSAIC), so the
# cart firmware and the MAME device must be from a tree that has them.
#
# Env:
#   ENDPOINT=...       server (default https://battleship.carr-designs.com/)
#   DEMO=1             the static position (tools/mkdemo.py), no network
#   FUJI_FIRMWARE=...  firmware tree (default ~/Workspace/fujinet-firmware)
#   ASL=...            the assembler (default ~/asl/asl, else asl on PATH)
set -euo pipefail
cd "$(dirname "$0")"

FUJI_FIRMWARE="${FUJI_FIRMWARE:-$HOME/Workspace/fujinet-firmware}"
TOOLS="$FUJI_FIRMWARE/pico/studio2/tools"
[ -f "$TOOLS/mkst2.py" ] || { echo "build.sh: no $TOOLS/mkst2.py (set FUJI_FIRMWARE)" >&2; exit 1; }

ASL=${ASL:-$HOME/asl/asl}
[ -x "$ASL" ] || ASL=$(command -v asl) || { echo "build.sh: no asl (Macroassembler AS)" >&2; exit 1; }

mkdir -p build

# Regenerated every run so a stale server cannot survive an environment change.
# The devicespec carries its own N: unless the endpoint already names a unit.
ENDPOINT="${ENDPOINT:-https://battleship.carr-designs.com/}"
case "$ENDPOINT" in
    N:*|N[1-8]:*) SPEC="$ENDPOINT" ;;
    *)            SPEC="N:$ENDPOINT" ;;
esac
cat > build/endpoint.inc <<EOC
; GENERATED by build.sh -- do not edit.
UENDPT: DB      "$SPEC", 0
EOC
cat > build/flags.inc <<EOC
; GENERATED by build.sh -- do not edit.
DEMO    EQU     ${DEMO:-0}
EOC
python3 tools/mkdemo.py build/demo.inc

(cd src && "$ASL" -q -U -L -i . -i ../build -o ../build/battleship.p \
    -olist ../build/battleship.lst battleship.asm)
python3 "$TOOLS/checkrom.py" build/battleship.lst
python3 "$TOOLS/mkst2.py" build/battleship.p build/battleship.st2 BATTLESHIP
