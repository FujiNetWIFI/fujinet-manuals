#!/usr/bin/env python3
"""mkdemo.py -- the canned four-seat state the DEMO build draws, as AS source.

Serialized exactly as the server's util.go serializeResults() does for
?bin=1&v=2: playerCount, prompt[33], status, playerStatus, activePlayer,
moveTime, lastAttackPos, myShips[10], then per player name[9], status,
gamefield[100], shipsLeft[5]. Names lower case and NUL padded.

The position: mid-game, our turn (activePlayer 0), the last shot a HIT. Seat
3 has been sunk outright; the others have lost a ship or two, so every tile
-- sea, hit, miss, hull, hit hull, both pips -- is on screen at once.

    python3 tools/mkdemo.py build/demo.inc
"""

import random
import sys

SIZES = [5, 4, 3, 3, 2]


def squares(pos, d, size):
    x, y = pos % 10, pos // 10
    return [(y + (i if d else 0)) * 10 + x + (0 if d else i) for i in range(size)]


def fleet(rng):
    """Five legal ships, as (pos, dir) pairs."""
    while True:
        taken, ships = set(), []
        for size in SIZES:
            for _ in range(200):
                d = rng.randrange(2)
                x, y = rng.randrange(10), rng.randrange(10)
                if (y if d else x) + size > 10:
                    continue
                sq = squares(y * 10 + x, d, size)
                if taken.isdisjoint(sq):
                    taken.update(sq)
                    ships.append((y * 10 + x, d))
                    break
            else:
                break
        if len(ships) == 5:
            return ships


def fstr(s, n):
    b = s.lower().encode()[:n]
    return list(b) + [0] * (n + 1 - len(b))


def player(rng, name, status, ships, shots, sink_all=False):
    field = [0] * 100
    left = [1] * 5
    for i, (pos, d) in enumerate(ships):
        sq = squares(pos, d, SIZES[i])
        if sink_all or i in shots.get("sunk", ()):
            for p in sq:
                field[p] = 1
            left[i] = 0
        else:
            for p in sq[: shots.get("hits", {}).get(i, 0)]:
                field[p] = 1
    hull = {p for i, (pos, d) in enumerate(ships) for p in squares(pos, d, SIZES[i])}
    water = [p for p in range(100) if p not in hull]
    for p in rng.sample(water, shots.get("misses", 0)):
        field[p] = 2
    return fstr(name, 8) + [status] + field + left, ships


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "build/demo.inc"
    rng = random.Random(2600)
    seats = [
        ("s2test", 0, {"hits": {0: 2, 2: 1}, "sunk": [4], "misses": 9}, False),
        ("clyde", 0, {"hits": {1: 3}, "sunk": [3], "misses": 12}, False),
        ("hulk bot", 0, {"hits": {0: 1, 2: 2}, "misses": 7}, False),
        ("jim", 1, {"misses": 15}, True),
    ]
    recs, ours = [], None
    for name, status, shots, sunk in seats:
        rec, ships = player(rng, name, status, fleet(rng), shots, sunk)
        recs.append(rec)
        if ours is None:
            ours = ships
    my_ships = [pos + 100 * d for pos, d in ours] + [0] * 5
    buf = [len(seats)] + fstr("", 32) + [12, 0, 0, 38, 47] + my_ships
    for rec in recs:
        buf += rec
    assert len(buf) == 49 + 115 * len(seats), len(buf)

    with open(out, "w") as f:
        f.write("; GENERATED by tools/mkdemo.py -- do not edit.\n")
        f.write("; A four-seat state as /state?bin=1&v=2 answers it: our turn,\n")
        f.write("; the last shot a hit, seat 3 sunk. %d bytes.\n" % len(buf))
        f.write("DEMOREP:\n")
        for i in range(0, len(buf), 16):
            f.write("        DB      %s\n" % ", ".join("%3d" % b for b in buf[i:i + 16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
