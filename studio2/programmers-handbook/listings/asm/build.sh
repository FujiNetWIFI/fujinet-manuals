#!/usr/bin/env bash
# build.sh -- this handbook's 1802 programs, with Macroassembler AS.
#
#   ./build.sh                    every program
#   ./build.sh netget clock       just those
#
# Each program is build/<name>.st2, what the cartridge serves. AS runs
# case-sensitive (-U). The runtime (../runtime) is the firmware's testrom,
# verbatim; build/gen/bookcfg.inc carries the bench's URLs and paths.
set -euo pipefail
cd "$(dirname "$0")"
BOOK=$(cd ../.. && pwd)
. "$BOOK/bench/ports.env"

ASL=${ASL:-$HOME/asl/asl}
[ -x "$ASL" ] || ASL=$(command -v asl) || { echo "build.sh: no asl" >&2; exit 1; }
TOOLS=../runtime/tools
mkdir -p build/gen build/obj

HOST=${HOST:-127.0.0.1}
cat > build/gen/bookcfg.inc <<EOC
; GENERATED by build.sh -- do not edit.
HTTP_URL MACRO
        DB      "N:http://$HOST:$HTTP_PORT/hello.txt", 0
        ENDM
NC_URL  MACRO
        DB      "N:TCP://$HOST:$NC_PORT/", 0
        ENDM
EOC
# fujiboot's own config, as the firmware's build.sh writes it
cat > build/gen/bootcfg.inc <<EOC
; GENERATED by build.sh -- do not edit.
BOOTHST EQU     ${BOOT_HOST:-0}
BOOTPATH MACRO
        DB      "${BOOT_PATH:-/s2book/hello.st2}", 0
        ENDM
EOC

build_one() {
    local name=$1 src
    if [ -f "$name.asm" ]; then src=.; else src=../runtime; fi
    [ -f "$src/$name.asm" ] || { echo "build.sh: no $name.asm" >&2; exit 1; }
    # relative paths: AS truncates a long include list
    local r
    r=$(realpath --relative-to="$src" .)
    (cd "$src" && "$ASL" -q -U -L -i "$r:$r/../runtime:$r/build/gen" \
        -o "$r/build/obj/$name.p" -olist "$r/build/obj/$name.lst" "$name.asm")
    python3 "$TOOLS/checkrom.py" "build/obj/$name.lst"
    python3 "$TOOLS/mkst2.py" "build/obj/$name.p" "build/$name.st2"
}

targets=("$@")
[ ${#targets[@]} -gt 0 ] || targets=(hello fujitest fujiboot netget fujidir appkey clock keys glyphs pages netcat)
for t in "${targets[@]}"; do
    build_one "$t"
done
