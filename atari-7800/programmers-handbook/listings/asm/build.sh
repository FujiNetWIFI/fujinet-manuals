#!/usr/bin/env bash
# build.sh -- build the assembly programs with cc65's ca65 and ld65, the way
# the bring-up's build.sh builds its clients: the program plus the shared
# start-up (a78init), text (fujidisp) and mailbox library (fujilib) from
# ../common, linked by a78.cfg (a78bank.cfg for a banked program), checked by
# checkrom.py and given the .a78 header MAME needs.
#
#   ./build.sh fujitest netget         -> build/fujitest.bin, build/fujitest.a78, ...
#   BOOT_PATH=/a7800book/hello.bin ./build.sh fujiboot
set -euo pipefail
cd "$(dirname "$0")"
BOOK="$(cd ../.. && pwd)"
mkdir -p build/gen build/obj

python3 "$BOOK/tools/mkfont.py" > build/gen/font.inc
cat > build/gen/bootcfg.inc <<EOC
; GENERATED by build.sh -- do not edit.
BOOTHST = ${BOOT_HOST:-0}
.define BOOTPATH "${BOOT_PATH:-/a7800book/hello.bin}"
BOOTDIRECT = ${BOOT_DIRECT:-0}
EOC

SHARED="a78init fujidisp fujilib"
for name in "$@"; do
    objs=() cfg=../common/a78.cfg defs=()
    src=$name.s
    [ -f "$src" ] || src=../common/$name.s
    if [ "$name" = fujibank ]; then
        cfg=../common/a78bank.cfg
        defs=(-D BANKED)
    fi
    for f in $SHARED; do
        ca65 -I . -I ../common -I build/gen "${defs[@]}" -o "build/obj/$f.o" "../common/$f.s"
        objs+=("build/obj/$f.o")
    done
    ca65 -I . -I ../common -I build/gen "${defs[@]}" -o "build/obj/$name.o" "$src"
    objs+=("build/obj/$name.o")
    ld65 -C "$cfg" -m "build/obj/$name.map" -o "build/$name.bin" "${objs[@]}"
    python3 "$BOOK/tools/checkrom.py" --claim --notia --map "build/obj/$name.map" "build/$name.bin"
    python3 "$BOOK/tools/mka78.py" "build/$name.bin" "build/$name.a78" "FUJINET $name"
done
