;	FLASHMODE - PUT THE H89 FUJINET'S ESP32 IN DOWNLOAD MODE
;
;	KEYED INTO THE MONITOR AT 040.100 AND RUN WITH G040100, FOR
;	MONITORS WITHOUT AN OUT COMMAND (MTR-88, MTR-89).  RESTARTS
;	THE ESP32 WITH IO0 LOW, SO IT WAITS FOR THE FUJINET FLASHER.
;	PUSH SHIFT AND RESET WHEN THE FLASHER IS DONE.
;
;	Copyright (C) 2026 Thomas Cherryhomes
;	SPDX-License-Identifier: GPL-3.0-or-later
;
PSTAT	EQU	322Q		;82C55 PORT C
PCTRL	EQU	323Q		;82C55 CONTROL WORD
;
	ORG	040100A
;
START:	MVI	A,300Q		;MODE 2: EN=0 AND IO0=0
	OUT	PCTRL
	LXI	H,0		;HOLD THE ESP32 IN RESET A WHILE
DELAY:	DCX	H
	MOV	A,H
	ORA	L
	JNZ	DELAY
	MVI	A,004Q		;EN=1 WITH IO0=0: DOWNLOAD MODE
	OUT	PSTAT
	HLT			;BACK TO THE MONITOR
;
	END	START
