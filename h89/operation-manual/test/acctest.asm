;	ACCTEST - H89 FUJINET ACCEPTANCE TEST
;
;	KEYED INTO THE MONITOR AT 040.100 AND RUN WITH G040100.
;	STARTS THE CARD, ASKS IT FOR ITS ADAPTER CONFIGURATION AND
;	PRINTS THE ANSWER.  PRINTS 1 WHEN THE 82C55 ANSWERS, 2 WHEN
;	THE ESP32 HAS TAKEN THE REQUEST, THEN THE REPLY'S TEXT.  ENDS
;	WITH A HALT, WHICH THE MONITOR TURNS INTO A BEEP, AN H AND
;	THE H: PROMPT.
;
;	NUMBERS ARE OCTAL (Q) OR SPLIT OCTAL (A), AS IN HEATH LISTINGS.
;
;	Copyright (C) 2026 Thomas Cherryhomes
;	SPDX-License-Identifier: GPL-3.0-or-later
;
PDATA	EQU	320Q		;82C55 PORT A, THE BYTE PIPE
PSTAT	EQU	322Q		;82C55 PORT C: STATUS IN, CONTROL OUT
PCTRL	EQU	323Q		;82C55 CONTROL WORD
WCC	EQU	003302A		;MONITOR: WRITE CONSOLE CHARACTER
;
	ORG	040100A
;
START:	MVI	A,300Q		;PORT A MODE 2, PC0-PC2 OUT:
	OUT	PCTRL		; EN=0 HOLDS THE ESP32 IN RESET
	MVI	A,006Q		;EN=1 WITH IO0=1: BOOT FROM FLASH
	OUT	PSTAT
	LXI	H,0		;WAIT ABOUT 3/4 SECOND SO THE
DELAY:	DCX	H		; ESP32 LATCHES IO0 BEFORE THE
	MOV	A,H		; 245 IS TURNED ON
	ORA	L
	JNZ	DELAY
	MVI	A,005Q		;245 ON (/OE=0), DIR TOWARD ESP32
	OUT	PSTAT
	IN	PSTAT		;IS THE 82C55 THERE?
	ANI	007Q		; PC2-PC0 MUST READ BACK 101
	CPI	005Q
	JNZ	DONE		;NO: HALT NOW
	MVI	A,'1'		;CHECKPOINT 1
	CALL	WCC
	LXI	H,REQ		;SEND THE REQUEST
	MVI	B,8
SEND:	MOV	A,M
	OUT	PDATA
WOBF:	IN	PSTAT		;WAIT UNTIL THE ESP32 HAS IT
	ANI	200Q		; (/OBF HIGH AGAIN)
	JZ	WOBF
	INX	H
	DCR	B
	JNZ	SEND
	MVI	A,004Q		;DIR TOWARD THE H89
	OUT	PSTAT
	MVI	A,'2'		;CHECKPOINT 2
	CALL	WCC
SYNC:	LXI	B,002400Q	;B=5 HEADER BYTES TO SKIP, C=0
HEAD:	CALL	GETB		;FIND THE FRAME, SKIP THE HEADER
	CPI	300Q		; (START OVER ON EVERY C0)
	JZ	SYNC
	DCR	B
	JNZ	HEAD
SHOW:	CALL	GETB		;PRINT THE REPLY UP TO THE END C0
	CPI	300Q
	JZ	DONE
	CPI	041Q		;PRINTABLE?
	JC	GAP
	CPI	177Q
	JC	PUT
GAP:	MVI	A,040Q		;ANYTHING ELSE IS A SPACE,
	CMP	C		; BUT ONLY ONE IN A ROW
	JZ	SHOW
PUT:	MOV	C,A
	CALL	WCC
	JMP	SHOW
;
GETB:	IN	PSTAT		;WAIT FOR A BYTE FROM THE ESP32
	ANI	040Q		; (IBF HIGH)
	JZ	GETB
	IN	PDATA
	RET
;
;	THE HALT COMES LAST: THE MONITOR'S CLOCK SEES A HALT WHEN THE
;	BYTE BEFORE THE INTERRUPTED ADDRESS IS 166Q, SO NO CODE MAY
;	FOLLOW ONE.
DONE:	HLT			;BACK TO THE MONITOR
;
;	GET ADAPTER CONFIG (350Q) FOR THE FUJINET DEVICE (160Q),
;	A SIX-BYTE FUJIBUS HEADER BETWEEN SLIP END BYTES (300Q).
REQ:	DB	300Q,160Q,350Q,006Q,000Q,137Q,000Q,300Q
;
	END	START
