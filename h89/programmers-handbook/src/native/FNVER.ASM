;	FNVER.ASM - ask the H89 FujiNet for its firmware version
;
;	Sets up the card's 82C55, sends FUJI_GET_ADAPTERCONFIG
;	(device 70H, command 0E8H) in a SLIP frame, checks the reply
;	and prints the network name and firmware version. Pure 8080.
;
;	A>ASM B:FNVER
;	A>LOAD B:FNVER
;	A>B:FNVER
;
;	Copyright (C) 2026 Thomas Cherryhomes
;	SPDX-License-Identifier: GPL-3.0-or-later
;
PORTA	EQU	0D0H		;82C55 PORT A, THE BYTE PIPE
PORTC	EQU	0D2H		;STATUS IN, PC0-PC2 OUT
PCTRL	EQU	0D3H		;CONTROL WORD, PORT C BIT SET/RESET
OBF	EQU	80H		;PC7 /OBF: 1 = OUR LAST BYTE WAS TAKEN
IBF	EQU	20H		;PC5 IBF: 1 = A BYTE WAITS FOR US
TICKS	EQU	000BH		;HEATH BIOS 2 MS CLOCK
TMAX	EQU	7500		;GIVE UP AFTER 15 S (7500 TICKS)
BDOS	EQU	0005H
SLEND	EQU	0C0H		;SLIP END: FRAMES A PACKET
SLESC	EQU	0DBH		;SLIP ESC
ESCEND	EQU	0DCH		;DB DC STANDS FOR A C0H
ESCESC	EQU	0DDH		;DB DD STANDS FOR A DBH
RMAX	EQU	200		;REPLY BUFFER SIZE
;
	ORG	0100H
;
START:	LXI	H,0		;KEEP THE CCP'S STACK POINTER
	DAD	SP
	SHLD	OLDSP
	LXI	SP,STACK	;AND USE OUR OWN
	CALL	CARDON		;SET UP THE CARD
	CALL	SENDRQ		;SEND THE REQUEST
	CALL	RECV		;TAKE THE REPLY
	CALL	CHECK		;CARRY: DE -> WHAT WAS WRONG
	JC	EXIT
	LXI	D,MNET
	CALL	PRMSG
	LXI	H,REPLY+6	;SSID: OFFSET 0, 33 BYTES
	MVI	B,33
	CALL	PRFLD
	LXI	D,MVER
	CALL	PRMSG
	LXI	H,REPLY+6+125	;FN_VERSION: OFFSET 125, 15 BYTES
	MVI	B,15
	CALL	PRFLD
	LXI	D,MEND
EXIT:	CALL	PRMSG
	LHLD	OLDSP		;BACK TO THE CCP
	SPHL
	RET
TMOUT:	LXI	D,MTIME
	JMP	EXIT		;(EXIT RESETS SP)
;
CARDON:	MVI	A,0C0H		;PORT A MODE 2, PC0-PC2 OUTPUTS:
	OUT	PCTRL		;PORT A GOES STRAIGHT TO THE ESP32
	IN	PORTA		;DROP ANY BYTE LATCHED BEFORE
	RET
;
SENDRQ:	LXI	H,PKT		;CHECKSUM THE PACKET, BYTE 4 AS 0
	MVI	B,6
	CALL	CKSUM
	STA	PKT+4
	MVI	A,SLEND		;ONE END BEFORE THE PACKET
	CALL	PUTC
	LXI	H,PKT
	MVI	B,6
SEND1:	MOV	A,M
	CPI	SLEND		;C0H GOES AS DB DC,
	MVI	C,ESCEND	;(MVI LEAVES THE FLAGS ALONE)
	JZ	SEND2
	CPI	SLESC		;DBH AS DB DD
	MVI	C,ESCESC
	JNZ	SEND3
SEND2:	MVI	A,SLESC
	CALL	PUTC
	MOV	A,C
SEND3:	CALL	PUTC
	INX	H
	DCR	B
	JNZ	SEND1
	MVI	A,SLEND		;ONE END AFTER IT
	CALL	PUTC
	CALL	TXWAIT		;UNTIL THE ESP32 HAS IT ALL
	RET
;
RECV:	CALL	GETC		;WAIT FOR AN END,
	CPI	SLEND
	JNZ	RECV
RECV1:	CALL	GETC		;SKIP ANY MORE
	CPI	SLEND
	JZ	RECV1
	LXI	H,REPLY		;HL -> BUFFER, C = BYTES KEPT
	MVI	C,0
RECV2:	CPI	SLEND		;THE CLOSING END: DONE
	RZ
	CPI	SLESC		;ESC: THE NEXT BYTE SAYS WHICH
	JNZ	RECV3
	CALL	GETC
	CPI	ESCEND		;DB DC WAS A C0H,
	MVI	A,SLEND
	JZ	RECV3
	MVI	A,SLESC		;DB DD A DBH
RECV3:	MOV	B,A		;KEEP IT IF THERE IS ROOM
	MOV	A,C
	CPI	RMAX
	JNC	RECV4
	MOV	M,B
	INX	H
	INR	C
RECV4:	CALL	GETC
	JMP	RECV2
;
CHECK:	MOV	A,C		;A HEADER AT LEAST
	CPI	6
	JC	BAD
	LHLD	REPLY+2		;LENGTH WORD = BYTES RECEIVED
	MOV	A,H
	ORA	A
	JNZ	BAD
	MOV	A,L
	CMP	C
	JNZ	BAD
	LXI	H,REPLY+4	;CHECKSUM: ITS OWN BYTE COUNTS AS 0
	MOV	E,M
	MVI	M,0
	LXI	H,REPLY
	MOV	B,C
	CALL	CKSUM
	CMP	E
	JNZ	BAD
	LXI	D,MNAK
	LDA	REPLY+1
	CPI	15H		;NAK: THE FUJINET SAID NO
	STC
	RZ
	CPI	06H		;ACK, WITH ALL 140 BYTES
	JNZ	BAD
	MOV	A,C
	CPI	6+140
	RNC
BAD:	LXI	D,MBAD
	STC
	RET
;
CKSUM:	XRA	A		;A = SUM OF B BYTES AT HL,
CKS1:	ADD	M		;WITH EACH CARRY ADDED BACK IN
	ACI	0
	INX	H
	DCR	B
	JNZ	CKS1
	RET
;
PUTC:	PUSH	PSW		;SEND A WHEN THE LATCH IS EMPTY
	CALL	TXWAIT
	POP	PSW
	OUT	PORTA
	RET
TXWAIT:	MVI	E,OBF		;WAIT FOR /OBF HIGH
	JMP	PCWAIT
GETC:	MVI	E,IBF		;A = THE NEXT BYTE FROM THE ESP32
	CALL	PCWAIT
	IN	PORTA
	RET
PCWAIT:	PUSH	H		;WAIT UNTIL PORT C HAS BIT E SET,
	LXI	H,TMAX		;FOR UP TO TMAX TICKS. KEEPS BC HL
	LDA	TICKS
	MOV	D,A		;D = THE TICK WE ARE IN
PCW1:	IN	PORTC
	ANA	E
	JNZ	PCW2
	LDA	TICKS		;HAS THE CLOCK TICKED?
	CMP	D
	JZ	PCW1
	MOV	D,A		;YES: ONE TICK FEWER LEFT
	DCX	H
	MOV	A,H
	ORA	L
	JNZ	PCW1
	JMP	TMOUT		;NONE LEFT: GIVE UP
PCW2:	POP	H
	RET
;
PRFLD:	MOV	A,M		;PRINT UP TO B CHARACTERS AT HL,
	ORA	A		;STOPPING AT A NUL
	RZ
	PUSH	H
	PUSH	B
	MOV	E,A
	MVI	C,2		;BDOS CONSOLE OUTPUT
	CALL	BDOS
	POP	B
	POP	H
	INX	H
	DCR	B
	JNZ	PRFLD
	RET
PRMSG:	MVI	C,9		;BDOS PRINT STRING, TO THE $
	JMP	BDOS
;
PKT:	DB	70H,0E8H,6,0,0,0 ;DEV, CMD, LENGTH, CHECKSUM, DESC
MNET:	DB	'Network:  $'
MVER:	DB	0DH,0AH,'Firmware: $'
MEND:	DB	0DH,0AH,'$'
MBAD:	DB	'Bad reply',0DH,0AH,'$'
MNAK:	DB	'FujiNet said NAK',0DH,0AH,'$'
MTIME:	DB	'No reply',0DH,0AH,'$'
OLDSP:	DS	2		;THE CCP'S SP
REPLY:	DS	RMAX		;THE REPLY PACKET, UNESCAPED
	DS	64
STACK:
	END	START
