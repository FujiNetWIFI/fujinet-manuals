*	FNVERH.ASM - ASK THE H89 FUJINET FOR ITS FIRMWARE VERSION
*
*	THE HDOS TWIN OF FNVER.ASM, FOR HEATH'S ASM.  SETS UP THE
*	CARD'S 82C55, SENDS FUJI_GET_ADAPTERCONFIG (DEVICE 160Q,
*	COMMAND 350Q) IN A SLIP FRAME, CHECKS THE REPLY AND PRINTS
*	THE NETWORK NAME AND FIRMWARE VERSION.  PURE 8080.
*
*	>SY1:ASM SY1:FNVERH,SY1:FNVERH=SY1:FNVERH
*	>SY1:FNVERH
*
*	ASM.ABS, HOSDEF.ACM AND ASCII.ACM (FROM THE SOFTWARE TOOLS
*	DISK) ARE ON SY1: WITH THIS FILE.
*
*	Copyright (C) 2026 Thomas Cherryhomes
*	SPDX-License-Identifier: GPL-3.0-or-later
*
	XTEXT	HOSDEF		HDOS SYSTEM CALLS
	XTEXT	ASCII		NL, ENL
*
PORTA	EQU	320Q		D0H: 82C55 PORT A, THE BYTE PIPE
PORTC	EQU	322Q		STATUS IN, PC0-PC2 OUT
PCTRL	EQU	323Q		CONTROL WORD, PORT C BIT SET/RESET
OBF	EQU	200Q		PC7 /OBF: 1 = OUR LAST BYTE WAS TAKEN
IBF	EQU	040Q		PC5 IBF: 1 = A BYTE WAITS FOR US
TICKS	EQU	40033A		HDOS 2 MS CLOCK (.TICCNT IN MTR.ACM)
TMAX	EQU	7500		GIVE UP AFTER 15 S (7500 TICKS)
SLEND	EQU	300Q		SLIP END: FRAMES A PACKET
SLESC	EQU	333Q		SLIP ESC
ESCEND	EQU	334Q		333 334 STANDS FOR A 300
ESCESC	EQU	335Q		333 335 STANDS FOR A 333
RMAX	EQU	200		REPLY BUFFER SIZE
*
	ORG	42200A		WHERE HDOS LOADS A PROGRAM
*
START	CALL	CARDON		SET UP THE CARD
	CALL	SENDRQ		SEND THE REQUEST
	CALL	RECV		TAKE THE REPLY
	CALL	CHECK		CARRY: HL -> WHAT WAS WRONG
	JC	EXIT
	LXI	H,MNET
	SCALL	.PRINT
	LXI	H,REPLY+6	SSID: OFFSET 0, 33 BYTES
	MVI	B,33
	CALL	PRFLD
	LXI	H,MVER
	SCALL	.PRINT
	LXI	H,REPLY+6+125	FN_VERSION: OFFSET 125, 15 BYTES
	MVI	B,15
	CALL	PRFLD
	LXI	H,MEND
EXIT	SCALL	.PRINT		PRINT TO THE BYTE WITH BIT 7 SET
	XRA	A
	SCALL	.EXIT		BACK TO HDOS
TMOUT	LXI	H,MTIME
	JMP	EXIT
*
CARDON	MVI	A,300Q		PORT A MODE 2, PC0-PC2 OUTPUTS:
	OUT	PCTRL		PORT A GOES STRAIGHT TO THE ESP32
	IN	PORTA		DROP ANY BYTE LATCHED BEFORE
	RET
*
SENDRQ	LXI	H,PKT		CHECKSUM THE PACKET, BYTE 4 AS 0
	MVI	B,6
	CALL	CKSUM
	STA	PKT+4
	MVI	A,SLEND		ONE END BEFORE THE PACKET
	CALL	PUTC
	LXI	H,PKT
	MVI	B,6
SEND1	MOV	A,M
	CPI	SLEND		300 GOES AS 333 334,
	MVI	C,ESCEND	(MVI LEAVES THE FLAGS ALONE)
	JZ	SEND2
	CPI	SLESC		333 AS 333 335
	MVI	C,ESCESC
	JNZ	SEND3
SEND2	MVI	A,SLESC
	CALL	PUTC
	MOV	A,C
SEND3	CALL	PUTC
	INX	H
	DCR	B
	JNZ	SEND1
	MVI	A,SLEND		ONE END AFTER IT
	CALL	PUTC
	CALL	TXWAIT		UNTIL THE ESP32 HAS IT ALL
	RET
*
RECV	CALL	GETC		WAIT FOR AN END,
	CPI	SLEND
	JNZ	RECV
RECV1	CALL	GETC		SKIP ANY MORE
	CPI	SLEND
	JZ	RECV1
	LXI	H,REPLY		HL -> BUFFER, C = BYTES KEPT
	MVI	C,0
RECV2	CPI	SLEND		THE CLOSING END: DONE
	RZ
	CPI	SLESC		ESC: THE NEXT BYTE SAYS WHICH
	JNZ	RECV3
	CALL	GETC
	CPI	ESCEND		333 334 WAS A 300,
	MVI	A,SLEND
	JZ	RECV3
	MVI	A,SLESC		333 335 A 333
RECV3	MOV	B,A		KEEP IT IF THERE IS ROOM
	MOV	A,C
	CPI	RMAX
	JNC	RECV4
	MOV	M,B
	INX	H
	INR	C
RECV4	CALL	GETC
	JMP	RECV2
*
CHECK	MOV	A,C		A HEADER AT LEAST
	CPI	6
	JC	BAD
	LHLD	REPLY+2		LENGTH WORD = BYTES RECEIVED
	MOV	A,H
	ORA	A
	JNZ	BAD
	MOV	A,L
	CMP	C
	JNZ	BAD
	LXI	H,REPLY+4	CHECKSUM: ITS OWN BYTE COUNTS AS 0
	MOV	E,M
	MVI	M,0
	LXI	H,REPLY
	MOV	B,C
	CALL	CKSUM
	CMP	E
	JNZ	BAD
	LXI	H,MNAK
	LDA	REPLY+1
	CPI	025Q		NAK: THE FUJINET SAID NO
	STC
	RZ
	CPI	006Q		ACK, WITH ALL 140 BYTES
	JNZ	BAD
	MOV	A,C
	CPI	6+140
	RNC
BAD	LXI	H,MBAD
	STC
	RET
*
CKSUM	XRA	A		A = SUM OF B BYTES AT HL,
CKS1	ADD	M		WITH EACH CARRY ADDED BACK IN
	ACI	0
	INX	H
	DCR	B
	JNZ	CKS1
	RET
*
PUTC	PUSH	PSW		SEND A WHEN THE LATCH IS EMPTY
	CALL	TXWAIT
	POP	PSW
	OUT	PORTA
	RET
TXWAIT	MVI	E,OBF		WAIT FOR /OBF HIGH
	JMP	PCWAIT
GETC	MVI	E,IBF		A = THE NEXT BYTE FROM THE ESP32
	CALL	PCWAIT
	IN	PORTA
	RET
PCWAIT	PUSH	H		WAIT UNTIL PORT C HAS BIT E SET,
	LXI	H,TMAX		FOR UP TO TMAX TICKS. KEEPS BC HL
	LDA	TICKS
	MOV	D,A		D = THE TICK WE ARE IN
PCW1	IN	PORTC
	ANA	E
	JNZ	PCW2
	LDA	TICKS		HAS THE CLOCK TICKED?
	CMP	D
	JZ	PCW1
	MOV	D,A		YES: ONE TICK FEWER LEFT
	DCX	H
	MOV	A,H
	ORA	L
	JNZ	PCW1
	JMP	TMOUT		NONE LEFT: GIVE UP
PCW2	POP	H
	RET
*
PRFLD	MOV	A,M		PRINT UP TO B CHARACTERS AT HL,
	ORA	A		STOPPING AT A NUL
	RZ
	PUSH	H
	PUSH	B
	SCALL	.SCOUT		CONSOLE OUTPUT
	POP	B
	POP	H
	INX	H
	DCR	B
	JNZ	PRFLD
	RET
*
PKT	DB	160Q,350Q,6,0,0,0  DEV, CMD, LENGTH, CHECKSUM, DESC
MNET	DB	'NETWORK: ',' '+200Q
MVER	DB	NL,'FIRMWARE:',' '+200Q
MEND	DB	ENL
MBAD	DB	'BAD REPLY',ENL
MNAK	DB	'FUJINET SAID NAK',ENL
MTIME	DB	'NO REPLY',ENL
REPLY	DS	RMAX		THE REPLY PACKET, UNESCAPED
*
	END	START
