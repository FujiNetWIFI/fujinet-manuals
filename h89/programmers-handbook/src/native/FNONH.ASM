*	FNONH.ASM - ENABLE THE FUJINET CARD IN AN H89 (82C55 AT 320Q)
*
*	THE HDOS TWIN OF FNON.ASM, FOR HEATH'S ASM.  SETS THE 82C55
*	TO MODE 2, BOOTS THE ESP32 FROM FLASH AND TURNS THE 74LVC245
*	TOWARD THE H89.  LEAVES A CARD THAT IS ALREADY ON ALONE:
*	WHATEVER SETS THE CARD UP LEAVES 245Q IN PORT B, WHICH A RESET
*	OR ANOTHER MODE WORD CLEARS.  EN ALONE CAN'T TELL, AS AFTER A
*	RESET THE 82C55'S BUS HOLD CAN PULL PC2 HIGH.
*
*	>SY1:ASM SY1:FNONH,SY1:FNONH=SY1:FNONH
*	>SY1:FNONH
*
*	ASM.ABS, HOSDEF.ACM AND ASCII.ACM (FROM THE SOFTWARE TOOLS
*	DISK) ARE ON SY1: WITH THIS FILE.
*
