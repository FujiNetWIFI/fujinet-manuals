*	FNONH.ASM - ENABLE THE FUJINET CARD IN AN H89 (82C55 AT 320Q)
*
*	THE HDOS TWIN OF FNON.ASM, FOR HEATH'S ASM.  SETS THE 82C55
*	TO MODE 2, BOOTS THE ESP32 FROM FLASH AND TURNS THE 74LVC245
*	TOWARD THE H89.  LEAVES A CARD THAT IS ALREADY ON ALONE.
*
*	>SY1:ASM SY1:FNONH,SY1:FNONH=SY1:FNONH
*	>SY1:FNONH
*
*	ASM.ABS, HOSDEF.ACM AND ASCII.ACM (FROM THE SOFTWARE TOOLS
*	DISK) ARE ON SY1: WITH THIS FILE.
*
*	Copyright (C) 2026 Thomas Cherryhomes
*	SPDX-License-Identifier: GPL-3.0-or-later
*
	XTEXT	HOSDEF		HDOS SYSTEM CALLS: .PRINT, .EXIT
	XTEXT	ASCII		ENL: NEW LINE + 200Q, ENDS A LINE
*
PORTA	EQU	320Q		D0H: 82C55 PORT A, THE BYTE PIPE
PORTC	EQU	322Q		PC0 DIR, PC1 /OE (ESP32 IO0), PC2 EN
PCTRL	EQU	323Q		CONTROL WORD, PORT C BIT SET/RESET
*
	ORG	42200A		WHERE HDOS LOADS A PROGRAM
*
START	IN	PORTC
	ANI	004Q		EN HIGH: CARD ALREADY RUNNING
	JNZ	ISON
	MVI	A,300Q		PORT A MODE 2, PC0-PC2 OUTPUTS
	OUT	PCTRL		(CLEARS PORT C, SO EN GOES LOW)
	MVI	A,006Q		EN=1, IO0=1
	OUT	PORTC
	MVI	A,002Q		EN=0 WITH IO0 ALREADY HIGH
	OUT	PORTC
	LXI	B,100		HOLD RESET ABOUT 1 MS
	CALL	WAIT
	MVI	A,006Q		EN=1: IO0 HIGH = BOOT FROM FLASH
	OUT	PORTC
	LXI	B,17000		KEEP IO0 HIGH WHILE IT STARTS, ~200 MS
	CALL	WAIT
	IN	PORTA		DROP ANY BYTE LATCHED DURING RESET
	MVI	A,002Q		PC1=0: ENABLE THE 245
	OUT	PCTRL
	MVI	A,000Q		PC0=0: 245 DRIVES TOWARD THE H89
	OUT	PCTRL
	LXI	H,MSGON
	JMP	DONE
ISON	LXI	H,MSGRUN
DONE	SCALL	.PRINT		PRINT TO THE BYTE WITH BIT 7 SET
	XRA	A
	SCALL	.EXIT		BACK TO HDOS
*
WAIT	DCX	B		ABOUT 12 US A PASS AT 2 MHZ
	MOV	A,B
	ORA	C
	JNZ	WAIT
	RET
*
MSGON	DB	'FUJINET ENABLED',ENL
MSGRUN	DB	'FUJINET ALREADY ON',ENL
*
	END	START
