*	SPDX-License-Identifier: GPL-3.0-or-later
*
	XTEXT	HOSDEF		HDOS SYSTEM CALLS: .PRINT, .EXIT
	XTEXT	ASCII		ENL: NEW LINE + 200Q, ENDS A LINE
*
PORTA	EQU	320Q		D0H: 82C55 PORT A, THE BYTE PIPE
PORTB	EQU	321Q		UNWIRED: HOLDS MARK ONCE SET UP
PORTC	EQU	322Q		PC0 DIR, PC1 /OE (ESP32 IO0), PC2 EN
PCTRL	EQU	323Q		CONTROL WORD, PORT C BIT SET/RESET
MARK	EQU	245Q		0A5H, AS FUJINET-LIB LEAVES IT
*
	ORG	42200A		WHERE HDOS LOADS A PROGRAM
*
START	IN	PORTB
	CPI	MARK		MARK AND EN HIGH: ALREADY RUNNING
	JNZ	SETUP
	IN	PORTC
	ANI	004Q
	JNZ	ISON
SETUP	MVI	A,300Q		PORT A MODE 2, PC0-PC2 OUTPUTS
	OUT	PCTRL		(CLEARS PORT C, SO EN GOES LOW)
	MVI	A,006Q		EN=1, IO0=1 AT ONCE: A RUNNING ESP32
	OUT	PORTC		STAYS UP, ONE IN RESET BOOTS
	LXI	B,17000		KEEP IO0 HIGH WHILE IT STARTS, ~200 MS
	CALL	WAIT
	MVI	A,MARK		THE CARD IS SET UP
	OUT	PORTB
	IN	PORTA		DROP ANY BYTE LATCHED DURING RESET
	MVI	A,002Q		PC1=0: ENABLE THE 245
	OUT	PCTRL
	MVI	A,000Q		PC0=0: 245 DRIVES TOWARD THE H89
	OUT	PCTRL
	LXI	H,MSGON
	JMP	DONE
ISON	LXI	H,MSGRUN
DONE	SCALL	.PRINT		PRINT TO THE BYTE WITH BIT 7 SET
	XRA	A
	SCALL	.EXIT		BACK TO HDOS
*
WAIT	DCX	B		ABOUT 12 US A PASS AT 2 MHZ
	MOV	A,B
	ORA	C
	JNZ	WAIT
	RET
*
MSGON	DB	'FUJINET ENABLED',ENL
MSGRUN	DB	'FUJINET ALREADY ON',ENL
*
	END	START
