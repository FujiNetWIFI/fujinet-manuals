/* text.c -- byte-aligned 5x7 text, white (color 3) on black (color 0). */

#include "text.h"

#define SCREEN    ((unsigned char *)0x4000)
#define BYTEPL    40                    /* bytes per scanline            */
#define LINES     80                    /* visible scanlines: 10 rows    */
#define BIOSFNT   ((const unsigned char *)0x08e4)  /* 5x7, 7 bytes/glyph */

/* Lowercase glyphs, same format as the BIOS font (from CONFIG's
 * font.inc: pattern in the top 5 bits, 7 rows).
 */
static const unsigned char lcfont[26 * 7] = {
    0x00,0x00,0x70,0x08,0x78,0x88,0x78,   /* a */
    0x80,0x80,0xf0,0x88,0x88,0x88,0xf0,   /* b */
    0x00,0x00,0x78,0x80,0x80,0x80,0x78,   /* c */
    0x08,0x08,0x78,0x88,0x88,0x88,0x78,   /* d */
    0x00,0x00,0x70,0x88,0xf8,0x80,0x70,   /* e */
    0x30,0x48,0x40,0xe0,0x40,0x40,0x40,   /* f */
    0x00,0x78,0x88,0x88,0x78,0x08,0x70,   /* g */
    0x80,0x80,0xf0,0x88,0x88,0x88,0x88,   /* h */
    0x20,0x00,0x60,0x20,0x20,0x20,0x70,   /* i */
    0x10,0x00,0x30,0x10,0x10,0x90,0x60,   /* j */
    0x80,0x80,0x90,0xa0,0xc0,0xa0,0x90,   /* k */
    0x60,0x20,0x20,0x20,0x20,0x20,0x70,   /* l */
    0x00,0x00,0xd0,0xa8,0xa8,0xa8,0xa8,   /* m */
    0x00,0x00,0xf0,0x88,0x88,0x88,0x88,   /* n */
    0x00,0x00,0x70,0x88,0x88,0x88,0x70,   /* o */
    0x00,0xf0,0x88,0x88,0xf0,0x80,0x80,   /* p */
    0x00,0x78,0x88,0x88,0x78,0x08,0x08,   /* q */
    0x00,0x00,0xb0,0xc8,0x80,0x80,0x80,   /* r */
    0x00,0x00,0x78,0x80,0x70,0x08,0xf0,   /* s */
    0x40,0x40,0xe0,0x40,0x40,0x48,0x30,   /* t */
    0x00,0x00,0x88,0x88,0x88,0x98,0x68,   /* u */
    0x00,0x00,0x88,0x88,0x88,0x50,0x20,   /* v */
    0x00,0x00,0x88,0xa8,0xa8,0xa8,0x50,   /* w */
    0x00,0x00,0x88,0x50,0x20,0x50,0x88,   /* x */
    0x00,0x88,0x88,0x88,0x78,0x08,0x70,   /* y */
    0x00,0x00,0xf8,0x10,0x20,0x40,0xf8,   /* z */
};

void txt_clear(void)
{
    unsigned char *p = SCREEN;
    unsigned int n = LINES * BYTEPL;

    while (n--)
        *p++ = 0;
}

/* Expand the top 5 bits of a pattern byte to 2bpp, foreground color 3. */
static unsigned int expand(unsigned char pat)
{
    unsigned int px = 0;
    unsigned char b;

    for (b = 0; b < 8; ++b) {
        px <<= 2;
        if (pat & 0x80)
            px |= 3;
        pat <<= 1;
    }
    return px;
}

void txt_putc(unsigned char x, unsigned char y, char c)
{
    const unsigned char *glyph;
    unsigned char *cell;
    unsigned char r;
    unsigned int px;

    if (c >= 'a' && c <= 'z')
        glyph = lcfont + (c - 'a') * 7;
    else {
        if (c < 0x20 || c >= 0x64)
            c = '.';
        glyph = BIOSFNT + (c - 0x20) * 7;
    }
    cell = SCREEN + (unsigned int)y * 8 * BYTEPL + x * 2;
    for (r = 0; r < 8; ++r) {
        px = (r < 7) ? expand(glyph[r]) : 0;
        cell[0] = px >> 8;
        cell[1] = px & 0xff;
        cell += BYTEPL;
    }
}

void txt_puts(unsigned char x, unsigned char y, const char *s)
{
    while (*s && x < 20)
        txt_putc(x++, y, *s++);
}

void txt_hex(unsigned char x, unsigned char y, unsigned char v)
{
    static const char digits[] = "0123456789ABCDEF";

    txt_putc(x, y, digits[v >> 4]);
    txt_putc(x + 1, y, digits[v & 0x0f]);
}
