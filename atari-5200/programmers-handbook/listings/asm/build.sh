#!/usr/bin/env bash
# build.sh -- build the assembly programs into build/<name>.bin with ca65/ld65.
#
#   ./build.sh hello fujitest ...         the named programs
#   BOOT_HOST=0 BOOT_PATH=/a5200book/hello.a52 ./build.sh fujiboot
#
# A program is <name>.s here or in ../common (the bring-up's, verbatim),
# linked with the bring-up's library (a52init, fujidisp, fujilib) and
# checked by tools/checkrom.py. fujibank and bank also build their bank 0
# (bank0.s), as the bring-up's build.sh does.
set -euo pipefail
cd "$(dirname "$0")"
BOOK=$(cd ../.. && pwd)
COMMON=../common

mkdir -p build/gen build/obj
python3 "$BOOK/tools/mkfont.py" > build/gen/font.inc
cat > build/gen/bootcfg.inc <<EOC
; GENERATED by build.sh -- do not edit.
BOOTHST = ${BOOT_HOST:-0}
.define BOOTPATH "${BOOT_PATH:-/a5200book/hello.a52}"
EOC

src() { if [ -f "$1.s" ]; then echo "$1.s"; else echo "$COMMON/$1.s"; fi; }
asm() { ca65 -I . -I "$COMMON" -I build/gen -o "build/obj/$1.o" "$(src "$1")"; }

build_one() {
    local name=$1 objs=() cfg=$COMMON/a52.cfg
    case $name in fujibank|bank) cfg=$COMMON/a52bank.cfg ;; esac
    for f in a52init fujidisp fujilib $name; do
        asm "$f"
        objs+=("build/obj/$f.o")
    done
    ld65 -C "$cfg" -m "build/obj/$name.map" -Ln "build/obj/$name.lbl" \
        -o "build/$name.bin" "${objs[@]}"
    case $name in fujibank|bank) build_bank0 "$name" ;; esac
    python3 "$BOOK/tools/checkrom.py" --claim --map "build/obj/$name.map" "build/$name.bin"
}

# A banked program's bank 0 (bank0.s): its own $A000-$AFFF, linked against
# the common code's addresses from bank 1's label file, laid over a copy of
# bank 1.
build_bank0() {
    local name=$1
    python3 - "build/obj/$name.lbl" > build/gen/bank1syms.inc <<'EOP'
import re, sys
syms = dict((n, a) for a, n in re.findall(r"al ([0-9A-F]{6}) \.(\w+)", open(sys.argv[1]).read()))
print("; GENERATED by build.sh from bank 1's label file -- do not edit.")
for w in ("disp_at", "disp_str", "disp_putc", "disp_rpl", "adapter"):
    print("%s = $%s" % (w, syms[w][2:]))
EOP
    asm bank0
    ld65 -C "$COMMON/bank0.cfg" -o build/obj/bank0.bin build/obj/bank0.o
    python3 - "build/$name.bin" <<'EOP'
import sys
b1 = open(sys.argv[1], "rb").read()
b0 = bytearray(b1)
b0[0x6000:0x7000] = open("build/obj/bank0.bin", "rb").read()
open(sys.argv[1], "wb").write(bytes(b0) + b1)
EOP
}

for t in "$@"; do
    build_one "$t"
done
